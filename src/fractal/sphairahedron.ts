// --------------------------------------------------------- wall systems

interface WallLine {
  /** 2D unit normal of the cross-section line, pointing to the REMOVED
   * side; the wall hyperplane lifts it to (a0, 0, a1, 0…). */
  a: [number, number];
  h: number;
}

interface WallCorner {
  i: number;
  j: number;
  q: [number, number];
  angle: number;
}

interface WallSystem {
  lines: WallLine[];
  corners: WallCorner[];
  /** Per wall: the distance between its two corners (Lemma 3.5's w). */
  width: number[];
}

const RT3 = Math.sqrt(3);
const RT2 = Math.SQRT2;

function widths(corners: WallCorner[]): number[] {
  const d = (p: [number, number], q: [number, number]) =>
    Math.hypot(p[0] - q[0], p[1] - q[1]);
  return [
    d(corners[0].q, corners[1].q),
    d(corners[0].q, corners[2].q),
    d(corners[1].q, corners[2].q),
  ];
}

/** The equilateral system: removed sides x·½ ± √3z/2 ≥ h, −x ≥ h. Corner
 * angles π/3; corner(0,1) = (2h, 0), corner(0,2) = (−h, √3h), corner(1,2) =
 * (−h, −√3h). `h` is the inradius. */
function wallSystem333(h: number): WallSystem {
  const corners: WallCorner[] = [
    { i: 0, j: 1, q: [2 * h, 0], angle: Math.PI / 3 },
    { i: 0, j: 2, q: [-h, RT3 * h], angle: Math.PI / 3 },
    { i: 1, j: 2, q: [-h, -RT3 * h], angle: Math.PI / 3 },
  ];
  return {
    lines: [
      { a: [0.5, RT3 / 2], h },
      { a: [0.5, -RT3 / 2], h },
      { a: [-1, 0], h },
    ],
    corners,
    width: widths(corners),
  };
}

/** (π/2, π/3, π/6) at corners (0,1), (0,2), (1,2). */
function wallSystem236(): WallSystem {
  const corners: WallCorner[] = [
    { i: 0, j: 1, q: [1, 0], angle: Math.PI / 2 },
    { i: 0, j: 2, q: [0.5, RT3 / 2], angle: Math.PI / 3 },
    { i: 1, j: 2, q: [-0.5, -RT3 / 2], angle: Math.PI / 6 },
  ];
  return {
    lines: [
      { a: [RT3 / 2, 0.5], h: RT3 / 2 },
      { a: [0.5, -RT3 / 2], h: 0.5 },
      { a: [-RT3 / 2, 0.5], h: 0 },
    ],
    corners,
    width: widths(corners),
  };
}

/** (π/2, π/4, π/4) at corners (0,1), (0,2), (1,2). */
function wallSystem244(): WallSystem {
  const corners: WallCorner[] = [
    { i: 0, j: 1, q: [1, 0], angle: Math.PI / 2 },
    { i: 0, j: 2, q: [0, 1], angle: Math.PI / 4 },
    { i: 1, j: 2, q: [0, -1], angle: Math.PI / 4 },
  ];
  return {
    lines: [
      { a: [1 / RT2, 1 / RT2], h: 1 / RT2 },
      { a: [1 / RT2, -1 / RT2], h: 1 / RT2 },
      { a: [-1, 0], h: 0 },
    ],
    corners,
    width: widths(corners),
  };
}

/** The wall hyperplane in n dims: cross-section normal lifted; the height
 * axis (index 1) and any extra axis (index 3) untouched. */
function wallPlane(line: WallLine, dim: 3 | 4): SphairahedronPlane {
  const n = new Array<number>(dim).fill(0);
  n[0] = line.a[0];
  n[2] = line.a[1];
  return { n, h: line.h };
}

// --------------------------------------------------------- ball solving

interface BallSpec {
  /** The two walls meeting at this ball's ideal vertex. */
  corner: [number, number];
  /** Absolute height of the vertex (and centre). */
  height: number;
  /** Dihedral angle to wall `corner[0]`, then to wall `corner[1]`. */
  theta: [number, number];
  /** Pinned radius; absent, the tangency system solves for it. */
  radius?: number;
  name: string;
}

function dot(a: ArrayLike<number>, b: ArrayLike<number>): number {
  let s = 0;
  for (let i = 0; i < a.length; i++) s += a[i] * b[i];
  return s;
}

function dist(a: ArrayLike<number>, b: ArrayLike<number>): number {
  let s = 0;
  for (let i = 0; i < a.length; i++) s += (a[i] - b[i]) ** 2;
  return Math.sqrt(s);
}

function cross3(a: number[], b: number[]): number[] {
  return [
    a[1] * b[2] - a[2] * b[1],
    a[2] * b[0] - a[0] * b[2],
    a[0] * b[1] - a[1] * b[0],
  ];
}

/** Unit direction from the corner making angle theta[0] with wall
 * corner[0]'s solid normal and theta[1] with the other's — the unique
 * direction inside the solid wedge (Lemma 3.3(3), solid-side reading).
 * Throws when the two angles do not close the vertex (θa + θb + θab = π). */
function ballDirection(ws: WallSystem, spec: BallSpec): [number, number] {
  const [i, j] = spec.corner;
  const si: [number, number] = [-ws.lines[i].a[0], -ws.lines[i].a[1]];
  const sj: [number, number] = [-ws.lines[j].a[0], -ws.lines[j].a[1]];
  const proj = sj[0] * si[0] + sj[1] * si[1];
  let t: [number, number] = [sj[0] - proj * si[0], sj[1] - proj * si[1]];
  const tl = Math.hypot(t[0], t[1]);
  t = [t[0] / tl, t[1] / tl];
  const cosT = Math.cos(spec.theta[0]);
  const sinT = Math.sin(spec.theta[0]);
  const u: [number, number] = [
    si[0] * cosT + t[0] * sinT,
    si[1] * cosT + t[1] * sinT,
  ];
  const aJ = Math.acos(Math.max(-1, Math.min(1, u[0] * sj[0] + u[1] * sj[1])));
  if (Math.abs(aJ - spec.theta[1]) > 1e-9) {
    throw new Error(
      `ball ${spec.name}: direction angles (${spec.theta[0]}, ${aJ}) do ` +
        `not close the vertex`,
    );
  }
  return u;
}

/**
 * Solve the Lemma 3.5 tangency system for the radii. One equation per ball
 * pair sharing a wall:
 *   r1·sin θ1w + r2·sin θ2w = (w² + Δh²) / (2w),
 * linear in the unpinned radii; pinned ones substitute. Exact elimination,
 * no iteration. Throws when the equations and unknowns mismatch or the
 * system is singular.
 */
function solveBalls(
  ws: WallSystem,
  specs: BallSpec[],
  dim: 3 | 4,
): { radii: number[]; centers: number[][] } {
  const dirs = specs.map((s) => ballDirection(ws, s));
  const unpinned = specs.map((s) => s.radius === undefined);
  const unknowns = unpinned.filter(Boolean).length;
  const eqs: { a: number; b: number; w: number; rhs: number }[] = [];
  for (let a = 0; a < specs.length; a++) {
    for (let b = a + 1; b < specs.length; b++) {
      const shared = specs[a].corner.filter((w) => specs[b].corner.includes(w));
      if (shared.length !== 1) continue;
      const w = shared[0];
      const ww = ws.width[w];
      const dh = specs[a].height - specs[b].height;
      eqs.push({ a, b, w, rhs: (ww * ww + dh * dh) / (2 * ww) });
    }
  }
  if (eqs.length !== unknowns) {
    throw new Error(
      `tangency system has ${eqs.length} equations for ${unknowns} unknowns`,
    );
  }
  const col = new Map<number, number>();
  let next = 0;
  for (let i = 0; i < specs.length; i++) if (unpinned[i]) col.set(i, next++);
  const sinOf = (i: number, w: number) =>
    Math.sin(specs[i].theta[specs[i].corner.indexOf(w)]);
  const m: number[][] = eqs.map((e) => {
    const row = new Array<number>(unknowns + 1).fill(0);
    const ra = specs[e.a].radius;
    const rb = specs[e.b].radius;
    if (unpinned[e.a]) row[col.get(e.a) as number] += sinOf(e.a, e.w);
    else if (ra !== undefined) row[unknowns] -= ra * sinOf(e.a, e.w);
    if (unpinned[e.b]) row[col.get(e.b) as number] += sinOf(e.b, e.w);
    else if (rb !== undefined) row[unknowns] -= rb * sinOf(e.b, e.w);
    row[unknowns] += e.rhs;
    return row;
  });
  for (let i = 0; i < unknowns; i++) {
    let piv = i;
    for (let r = i + 1; r < m.length; r++)
      if (Math.abs(m[r][i]) > Math.abs(m[piv][i])) piv = r;
    [m[i], m[piv]] = [m[piv], m[i]];
    if (Math.abs(m[i][i]) < 1e-12)
      throw new Error("tangency system is singular");
    for (let r = 0; r < m.length; r++) {
      if (r === i) continue;
      const f = m[r][i] / m[i][i];
      for (let c = i; c <= unknowns; c++) m[r][c] -= f * m[i][c];
    }
  }
  const radii = specs.map((s, i) =>
    s.radius !== undefined
      ? s.radius
      : m[col.get(i) as number][unknowns] / m[col.get(i) as number][i],
  );
  const centers = specs.map((s, i) => {
    const corner = ws.corners.find(
      (c) => c.i === s.corner[0] && c.j === s.corner[1],
    );
    if (!corner) throw new Error(`no corner for ball ${s.name}`);
    const c = new Array<number>(dim).fill(0);
    c[0] = corner.q[0] + radii[i] * dirs[i][0];
    c[1] = s.height;
    c[2] = corner.q[1] + radii[i] * dirs[i][1];
    return c;
  });
  return { radii, centers };
}

// -------------------------------------------------------------- inversion

/** The inversion `I(x) = c + R²(x−c)/|x−c|²` in the sphere `j`. */
function invertPoint(j: SphairahedronSphere, p: readonly number[]): number[] {
  const d2 = dist(p, j.c) ** 2;
  const k = (j.r * j.r) / d2;
  return j.c.map((v, i) => v + k * (p[i] - v));
}

type HImage =
  | { kind: "sphere"; sphere: SphairahedronSphere }
  | { kind: "plane"; plane: SphairahedronPlane };

/** Image of a sphere: a sphere, or a plane when the surface passes through
 * the inversion centre. */
function invertSphere(j: SphairahedronSphere, s: SphairahedronSphere): HImage {
  const dc: number[] = s.c.map((v, i) => v - j.c[i]);
  const d2 = dot(dc, dc);
  const den = d2 - s.r * s.r;
  if (Math.abs(den) < 1e-9 * Math.max(1, d2)) {
    const len = Math.sqrt(d2);
    const n = dc.map((v) => v / len);
    return {
      kind: "plane",
      plane: { n, h: dot(j.c, n) + (j.r * j.r) / (2 * len) },
    };
  }
  const k = (j.r * j.r) / den;
  return {
    kind: "sphere",
    sphere: { c: j.c.map((v, i) => v + k * dc[i]), r: Math.abs(k) * s.r },
  };
}

/** Image of a plane: a sphere through the inversion centre, or the plane
 * itself when the centre lies on it. */
function invertPlane(j: SphairahedronSphere, pl: SphairahedronPlane): HImage {
  const d = dot(pl.n, j.c) - pl.h;
  if (Math.abs(d) < 1e-12 * Math.max(1, j.r)) {
    return { kind: "plane", plane: { n: [...pl.n], h: pl.h } };
  }
  const k = (j.r * j.r) / (2 * d);
  return {
    kind: "sphere",
    sphere: { c: j.c.map((v, i) => v - k * pl.n[i]), r: Math.abs(k) },
  };
}

// -------------------------------------------------------------- the tile

function termSDF(t: SphairahedronTerm, p: ArrayLike<number>): number {
  if (t.kind === "sphere") {
    const d = dist(p, t.c) - t.r;
    return t.inside ? d : -d;
  }
  const d = dot(t.n, p) - t.h;
  return t.above ? -d : d;
}

/** The tile SDF: max-form intersection per piece, min over pieces.
 * Negative inside the union of tiles, positive outside — the reference
 * implementation's exact convention. */
export function sphairahedronTileSDF(
  construction: SphairahedronConstruction,
  p: ArrayLike<number>,
): number {
  let best = Infinity;
  for (const piece of construction.pieces) {
    let d = -Infinity;
    for (const t of piece.terms) {
      const v = termSDF(t, p);
      if (v > d) d = v;
    }
    if (d < best) best = d;
  }
  return best;
}

// ------------------------------------------------------------- the fold

/** Scratch for the fold: the folded point, the accumulated conformal
 * Jacobian and the move counters. Reused across calls; no allocations in
 * the hot path. `lastFace` is the fold's last-move face index (−1 when it
 * never moved) — the per-face color attribution both readings carry. */
export interface SphairahedronScratch {
  x: Float64Array;
  moves: number;
  inversions: number;
  reflections: number;
  passes: number;
  capped: boolean;
  skippedPole: boolean;
  lambda: number;
  lastFace: number;
}

export function makeSphairahedronScratch(
  dim: 3 | 4,
  _cap: number,
): SphairahedronScratch {
  return {
    x: new Float64Array(dim),
    moves: 0,
    inversions: 0,
    reflections: 0,
    passes: 0,
    capped: false,
    skippedPole: false,
    lambda: 1,
    lastFace: -1,
  };
}

/**
 * The IIS fold (the estimator twins run this through their flattened
 * tables; this plain-data form is the vocabulary's own reading and the
 * tests' cross-check): per pass, scan the faces in order; a face sphere
 * holding the point on its REMOVED side inverts it (λ ×= R²/|p−c|²), a
 * violated wall reflects it (λ unchanged); the scan CONTINUES within the
 * pass and passes repeat until a clean one or the cap. The cap is a
 * numerical guard, not an object parameter — queries on the limit set
 * never fold in.
 */
export function foldSphairahedron(
  construction: SphairahedronConstruction,
  p: ArrayLike<number>,
  s: SphairahedronScratch,
): SphairahedronScratch {
  const dim = construction.dim;
  for (let i = 0; i < dim; i++) s.x[i] = p[i];
  s.moves = 0;
  s.inversions = 0;
  s.reflections = 0;
  s.passes = 0;
  s.capped = false;
  s.skippedPole = false;
  s.lambda = 1;
  s.lastFace = -1;
  for (;;) {
    let moved = false;
    for (
      let faceIndex = 0;
      faceIndex < construction.foldFaces.length;
      faceIndex++
    ) {
      const { face, solidInside } = construction.foldFaces[faceIndex];
      if (face.kind === "sphere") {
        const c = face.sphere.c;
        const r = face.sphere.r;
        let d2 = 0;
        for (let i = 0; i < dim; i++) {
          const t = s.x[i] - c[i];
          d2 += t * t;
        }
        const onRemovedSide = solidInside ? d2 > r * r : d2 < r * r;
        if (onRemovedSide) {
          if (
            d2 <
            SPHAIRAHEDRON_POLE_FLOOR * SPHAIRAHEDRON_POLE_FLOOR * r * r
          ) {
            s.skippedPole = true;
            continue;
          }
          const k = (r * r) / d2;
          for (let i = 0; i < dim; i++) s.x[i] = c[i] + k * (s.x[i] - c[i]);
          s.lambda *= k;
          s.inversions++;
          s.moves++;
          s.lastFace = faceIndex;
          moved = true;
        }
      } else {
        const pl = face.plane;
        let d = -pl.h;
        for (let i = 0; i < dim; i++) d += pl.n[i] * s.x[i];
        if (d > 0) {
          for (let i = 0; i < dim; i++) s.x[i] -= 2 * d * pl.n[i];
          s.reflections++;
          s.moves++;
          s.lastFace = faceIndex;
          moved = true;
        }
      }
    }
    s.passes++;
    if (!moved) break;
    if (s.passes >= construction.foldCap) {
      s.capped = true;
      break;
    }
  }
  return s;
}

/** Membership in the union of tiles: the fold terminates within the cap AND
 * the folded point satisfies the tile's own conditions (the fold does not
 * test the divide plane, so termination alone is weaker). A skipped pole is
 * not a member. */
export function sphairahedronContains(
  construction: SphairahedronConstruction,
  p: ArrayLike<number>,
  s: SphairahedronScratch,
): boolean {
  foldSphairahedron(construction, p, s);
  if (s.skippedPole) return false;
  return !s.capped && sphairahedronTileSDF(construction, s.x) <= 0;
}

// ------------------------------------------------------- the construction

interface BuildOptions {
  dim: 3 | 4;
  ws: WallSystem;
  balls: BallSpec[];
  /** Explicit divide hyperplane; absent, the plane through the corner
   * vertices. */
  divide?: SphairahedronPlane;
}

/** The built infinite scene: the construction's geometry plus the combined
 * face list and vertices the finite mapping and the seeds read. */
interface BuiltScene {
  dim: 3 | 4;
  foldFaces: SphairahedronFoldFace[];
  pieces: SphairahedronTilePiece[];
  /** Combined face list for the finite mapping: balls then walls. */
  faces: SphairahedronFace[];
  vertices: { p: number[]; faces: number[] }[];
  probe: number[];
  divide: SphairahedronPlane;
  bound: { center: number[]; radius: number };
  seeds: SphairahedronSeedBall[];
  foldCap: number;
  radii: number[];
  ballCenters: number[][];
  verification: SphairahedronVerification;
}

/** Assemble the infinite sphairahedron: solve the radii, verify Lemmas
 * 3.3/3.5 numerically, build the vertices, the divide plane, the tile and
 * the maximum vertex balls. Throws on a construction that cannot be built
 * (singular tangency system, no divide plane); verification problems are
 * REPORTED, not thrown — the analyzer turns them into reasons. */
function buildInfinite(opts: BuildOptions): { scene: BuiltScene } {
  const { dim, ws, balls } = opts;
  const { radii, centers } = solveBalls(ws, balls, dim);
  const ballCount = radii.length;
  const problems: string[] = [];
  let maxTangentErr = 0;
  let maxAngleErr = 0;
  const extraCrossings: Record<string, number[]> = {};

  // Lemma 3.3(2): the ball is tangent to its corner line; 3.3(3) read as
  // the plane/sphere dihedral: cos θ = δ/r.
  balls.forEach((spec, i) => {
    const corner = ws.corners.find(
      (c) => c.i === spec.corner[0] && c.j === spec.corner[1],
    ) as WallCorner;
    const d = Math.hypot(
      centers[i][0] - corner.q[0],
      centers[i][2] - corner.q[1],
    );
    maxTangentErr = Math.max(maxTangentErr, Math.abs(d - radii[i]));
    if (radii[i] <= 0)
      problems.push(`ball ${spec.name}: radius ${radii[i]} <= 0`);
    spec.corner.forEach((w, k) => {
      const pl = wallPlane(ws.lines[w], dim);
      const delta = Math.abs(dot(pl.n, centers[i]) - pl.h);
      const angle = Math.acos(Math.max(-1, Math.min(1, delta / radii[i])));
      maxAngleErr = Math.max(maxAngleErr, Math.abs(angle - spec.theta[k]));
    });
    // Any wall the ball additionally crosses is reported (the prism's
    // second vertex lives on one).
    const extra: number[] = [];
    for (let w = 0; w < ws.lines.length; w++) {
      if (spec.corner.includes(w)) continue;
      const pl = wallPlane(ws.lines[w], dim);
      const delta = Math.abs(dot(pl.n, centers[i]) - pl.h);
      if (delta < radii[i] * (1 - 1e-12)) extra.push(w);
    }
    if (extra.length > 0) extraCrossings[spec.name] = extra;
  });

  // Vertices: each ball's corner vertex, plus any extra corner-line
  // contacts (the prism family's second vertex lives on one).
  const vertices: { p: number[]; faces: number[] }[] = [];
  balls.forEach((spec, i) => {
    const corner = ws.corners.find(
      (c) => c.i === spec.corner[0] && c.j === spec.corner[1],
    ) as WallCorner;
    const p = new Array<number>(dim).fill(0);
    p[0] = corner.q[0];
    p[1] = spec.height;
    p[2] = corner.q[1];
    vertices.push({
      p,
      faces: [i, ballCount + spec.corner[0], ballCount + spec.corner[1]],
    });
    for (const w of extraCrossings[spec.name] ?? []) {
      for (const cc of ws.corners.filter((c) => c.i === w || c.j === w)) {
        const d = Math.hypot(centers[i][0] - cc.q[0], centers[i][2] - cc.q[1]);
        if (Math.abs(d - radii[i]) <= 1e-9 * Math.max(1, radii[i])) {
          const p2 = new Array<number>(dim).fill(0);
          p2[0] = cc.q[0];
          p2[1] = spec.height;
          p2[2] = cc.q[1];
          vertices.push({
            p: p2,
            faces: [i, ballCount + cc.i, ballCount + cc.j],
          });
        }
      }
    }
  });

  // Lemma 3.5: tangency of the wall circles per sharing pair. The circles
  // live in the wall plane with centres at the feet of the ball centres.
  const foot = (i: number, pl: SphairahedronPlane): number[] => {
    const d = dot(pl.n, centers[i]) - pl.h;
    return centers[i].map((v, k) => v - d * pl.n[k]);
  };
  for (let a = 0; a < balls.length; a++) {
    for (let b = a + 1; b < balls.length; b++) {
      const shared = balls[a].corner.find((w) => balls[b].corner.includes(w));
      if (shared === undefined) continue;
      const pl = wallPlane(ws.lines[shared], dim);
      const ra = Math.sqrt(
        Math.max(0, radii[a] ** 2 - dist(centers[a], foot(a, pl)) ** 2),
      );
      const rb = Math.sqrt(
        Math.max(0, radii[b] ** 2 - dist(centers[b], foot(b, pl)) ** 2),
      );
      const gap = dist(foot(a, pl), foot(b, pl)) - (ra + rb);
      maxTangentErr = Math.max(maxTangentErr, Math.abs(gap));
      if (Math.abs(gap) > 1e-7 * Math.max(1, ra + rb)) {
        problems.push(
          `balls ${balls[a].name}/${balls[b].name}: wall circles not tangent ` +
            `(gap ${gap.toExponential(2)})`,
        );
        continue;
      }
      const fa = foot(a, pl);
      const fb = foot(b, pl);
      const t = ra / (ra + rb);
      vertices.push({
        p: fa.map((v, i) => v + t * (fb[i] - v)),
        faces: [a, b, ballCount + shared],
      });
    }
  }

  // The three-ball vertex: the balls' common point where their pairwise
  // circles are mutually tangent (P246 for the cube).
  if (balls.length === 3) {
    const triple = tripleBallVertex(centers, radii);
    if (triple) vertices.push({ p: triple, faces: [0, 1, 2] });
    else problems.push("no common point of the three balls (P246 missing)");
  }

  // The divide plane.
  let divide: SphairahedronPlane | undefined = opts.divide;
  if (!divide) {
    const pts = vertices.filter((v) => v.faces.length === 3);
    if (pts.length < 3)
      throw new Error("need three corner vertices for the divide plane");
    divide = planeThrough3(pts[0].p, pts[1].p, pts[2].p, dim);
  }

  // Tile pieces.
  const terms: SphairahedronTerm[] = [
    ...ws.lines.map((l): SphairahedronTerm => ({
      kind: "plane",
      n: wallPlane(l, dim).n,
      h: l.h,
      above: false,
    })),
    ...radii.map((r, i): SphairahedronTerm => ({
      kind: "sphere",
      c: centers[i],
      r,
      inside: false,
    })),
  ];
  const probe = new Array<number>(dim).fill(0);
  probe[1] = Math.min(...balls.map((b) => b.height)) - 2;
  // Orient the divide's solid side by the probe.
  const dVal = dot(divide.n, probe) - divide.h;
  terms.push({
    kind: "plane",
    n: [...divide.n],
    h: divide.h,
    above: dVal > 0,
  });
  const pieces: SphairahedronTilePiece[] = [{ terms }];

  const faces: SphairahedronFace[] = [
    ...radii.map((r, i) => ({
      kind: "sphere" as const,
      sphere: { c: centers[i], r },
    })),
    ...ws.lines.map((l) => ({
      kind: "plane" as const,
      plane: wallPlane(l, dim),
    })),
  ];
  const scene = {
    dim,
    foldFaces: [
      ...radii.map((r, i) => ({
        face: {
          kind: "sphere" as const,
          sphere: { c: centers[i], r },
        },
        solidInside: false,
      })),
      ...ws.lines.map((l) => ({
        face: {
          kind: "plane" as const,
          plane: wallPlane(l, dim),
        },
        solidInside: false,
      })),
    ],
    pieces,
    faces,
    vertices,
    probe,
    divide,
    bound: frameBound(dim, balls, radii, centers),
    seeds: maxVertexBalls(faces, vertices, pieces),
    foldCap: SPHAIRAHEDRON_FOLD_CAP,
    radii,
    ballCenters: centers,
    verification: {
      maxTangentErr,
      maxAngleErr,
      problems,
      crossings: extraCrossings,
    },
  };
  return { scene };
}

/** One of the two common points of three spheres, chosen where their
 * pairwise circles are mutually tangent; null when they have no common
 * point or are not mutually tangent at either. Can degenerate to a
 * TANGENCY (disc ≈ 0⁻ — clamped, not rejected). */
function tripleBallVertex(
  centers: number[][],
  radii: number[],
): number[] | null {
  const [c0, c1, c2] = centers;
  const [r0, r1, r2] = radii;
  const l1 = c1.map((v, i) => 2 * (v - c0[i]));
  const l2 = c2.map((v, i) => 2 * (v - c0[i]));
  const k1 = dot(c1, c1) - r1 * r1 - (dot(c0, c0) - r0 * r0);
  const k2 = dot(c2, c2) - r2 * r2 - (dot(c0, c0) - r0 * r0);
  // Closest point to c0 on the radical line: p* = c0 + Lᵀ(LLᵀ)⁻¹(k − Lc0);
  // the tangent circles touch at p* ± √(r0² − |p*−c0|²) along the line.
  const dim = c0.length;
  const a00 = dot(l1, l1);
  const a01 = dot(l1, l2);
  const a11 = dot(l2, l2);
  const det = a00 * a11 - a01 * a01;
  if (Math.abs(det) < 1e-30) return null;
  const r1v = k1 - dot(l1, c0);
  const r2v = k2 - dot(l2, c0);
  const wa = (a11 * r1v - a01 * r2v) / det;
  const wb = (a00 * r2v - a01 * r1v) / det;
  const pStar = c0.map((v, i) => v + wa * l1[i] + wb * l2[i]);
  if (dim !== 3) return null;
  const dir = cross3(l1, l2);
  const dl = dot(dir, dir);
  if (dl < 1e-30) return null;
  const gap = dist(pStar, c0);
  let disc = r0 * r0 - gap * gap;
  if (disc < 0) {
    if (disc < -1e-9 * r0 * r0) return null;
    disc = 0;
  }
  const t = Math.sqrt(disc) / dl;
  const parallel = (p: number[]): number => {
    const t01 = cross3(
      p.map((v, i) => v - c0[i]),
      p.map((v, i) => v - c1[i]),
    );
    const t02 = cross3(
      p.map((v, i) => v - c0[i]),
      p.map((v, i) => v - c2[i]),
    );
    const t12 = cross3(
      p.map((v, i) => v - c1[i]),
      p.map((v, i) => v - c2[i]),
    );
    const u = Math.hypot(...t01);
    if (u < 1e-15) return Infinity;
    const n01 = t01.map((v) => v / u);
    const n02 = t02.map((v) => v / (Math.hypot(...t02) || 1));
    const n12 = t12.map((v) => v / (Math.hypot(...t12) || 1));
    return Math.max(1 - Math.abs(dot(n01, n02)), 1 - Math.abs(dot(n01, n12)));
  };
  const pPlus = dir.map((v, i) => pStar[i] + t * v);
  const pMinus = dir.map((v, i) => pStar[i] - t * v);
  const ePlus = parallel(pPlus);
  const eMinus = parallel(pMinus);
  if (Math.min(ePlus, eMinus) > 1e-6) return null;
  return ePlus <= eMinus ? pPlus : pMinus;
}

function planeThrough3(
  a: number[],
  b: number[],
  c: number[],
  dim: 3 | 4,
): SphairahedronPlane {
  const n = cross3(
    b.map((v, i) => v - a[i]),
    c.map((v, i) => v - a[i]),
  );
  const l = Math.hypot(...n);
  const u = n.map((v) => v / l);
  if (dim === 4) {
    // The 3D cross product of the two difference vectors lies in the
    // hyperplane spanned by them; for axis-aligned constructions the
    // normal needs no w component — refuse rather than guess.
    if (Math.abs(u[3]) > 1e-9)
      throw new Error("divide plane needs a w component; pass it explicitly");
    u.pop();
  }
  return { n: u, h: dot(u, a) };
}

function frameBound(
  dim: 3 | 4,
  balls: BallSpec[],
  radii: number[],
  centers: number[][],
): { center: number[]; radius: number } {
  const center = new Array<number>(dim).fill(0);
  let reach = 0;
  let lo = Infinity;
  let hi = -Infinity;
  balls.forEach((b, i) => {
    center[1] += b.height / balls.length;
    lo = Math.min(lo, centers[i][1] - radii[i]);
    hi = Math.max(hi, centers[i][1] + radii[i]);
    for (let k = 0; k < dim; k++)
      reach = Math.max(reach, Math.abs(centers[i][k]) + radii[i]);
  });
  reach = Math.max(reach, 3, (hi - lo) * 1.5 + 4);
  return { center, radius: reach };
}

// --------------------------------------------------- maximum vertex balls

/**
 * The maximum vertex balls (the preprint's Def 4.1): per vertex X, the open
 * ball whose boundary passes through X, is orthogonal to every edge there
 * (its centre on the common edge-tangent line — all three edge tangents
 * verified parallel, the ideality check), contains no other vertex, and is
 * maximal — the ball touching the nearest other vertex along its centre
 * line. Side chosen toward the tile interior; a vertex whose ball would be
 * a half-space (the ∞ vertex) yields no seed (the tetra families' case).
 */
function maxVertexBalls(
  faces: SphairahedronFace[],
  vertices: { p: number[]; faces: number[] }[],
  pieces: SphairahedronTilePiece[],
): SphairahedronSeedBall[] {
  const inTile = (p: number[]): boolean => {
    for (const piece of pieces) {
      let d = -Infinity;
      for (const t of piece.terms) d = Math.max(d, termSDF(t, p));
      if (d <= 0) return true;
    }
    return false;
  };
  const faceNormalAt = (f: SphairahedronFace, p: number[]): number[] => {
    if (f.kind === "sphere") {
      const d = dist(p, f.sphere.c);
      return f.sphere.c.map((v, i) => (p[i] - v) / d);
    }
    return [...f.plane.n];
  };
  const seeds: SphairahedronSeedBall[] = [];
  for (const v of vertices) {
    const normals = v.faces.map((fi) => faceNormalAt(faces[fi], v.p));
    const raw = cross3(normals[0], normals[1]);
    const tl = Math.hypot(...raw);
    if (tl < 1e-12) continue;
    const t2 = cross3(normals[0], normals[2]);
    const t2l = Math.hypot(...t2);
    if (t2l < 1e-12) continue;
    if (1 - Math.abs(dot(raw, t2) / (tl * t2l)) > 1e-6) continue;
    const unit = raw.map((x) => x / tl);
    for (const side of [1, -1]) {
      const tangent = unit.map((x) => x * side);
      let tStar = Infinity;
      for (const o of vertices) {
        if (o === v) continue;
        const dy: number[] = o.p.map((x, i) => x - v.p[i]);
        const along = dot(dy, tangent);
        if (along <= 1e-12) continue;
        const t = dot(dy, dy) / (2 * along);
        if (t < tStar) tStar = t;
      }
      if (!Number.isFinite(tStar) || tStar <= 1e-12) continue;
      const c = v.p.map((x, i) => x + tStar * tangent[i]);
      const test = v.p.map((x, i) => x + tangent[i] * tStar * 0.5);
      if (!inTile(test)) continue;
      seeds.push({ c, r: tStar });
      break;
    }
  }
  return seeds;
}

// ----------------------------------------------------- finite construction

/**
 * The finite sphairahedron: every face, tile term, vertex and seed of the
 * infinite scene mapped through the inversion sphere `j`; each image's
 * solid side fixed by mapping the probe (whose image is guaranteed
 * union-interior). The fold order interleaves walls and balls (the
 * reference's gSpheres order). The framing ball becomes the divide plane's
 * image — the quasi-sphere's smooth carrier — grown to hold the dent
 * spheres. Throws when a seed image degenerates to a plane (move J).
 */
function makeFinite(
  scene: BuiltScene,
  j: SphairahedronSphere,
): {
  foldFaces: SphairahedronFoldFace[];
  pieces: SphairahedronTilePiece[];
  probe: number[];
  bound: { center: number[]; radius: number };
  seeds: SphairahedronSeedBall[];
  vertices: SphairahedronVertex[];
} {
  const q0 = invertPoint(j, scene.probe);
  const mapImage = (img: HImage): SphairahedronTerm => {
    if (img.kind === "sphere") {
      const d = dist(q0, img.sphere.c) - img.sphere.r;
      return {
        kind: "sphere",
        c: img.sphere.c,
        r: img.sphere.r,
        inside: d < 0,
      };
    }
    const v = dot(img.plane.n, q0) - img.plane.h;
    return {
      kind: "plane",
      n: [...img.plane.n],
      h: img.plane.h,
      above: v > 0,
    };
  };
  const imageOfFace = (f: SphairahedronFace): HImage =>
    f.kind === "sphere" ? invertSphere(j, f.sphere) : invertPlane(j, f.plane);

  const pieces: SphairahedronTilePiece[] = scene.pieces.map((piece) => ({
    terms: piece.terms.map((t) =>
      t.kind === "sphere"
        ? mapImage(invertSphere(j, { c: t.c, r: t.r }))
        : mapImage(invertPlane(j, { n: t.n, h: t.h })),
    ),
  }));

  // Fold order: walls and balls interleaved (wall0, ball0, wall1, ball1,
  // wall2, ball2 …) when the counts match — the reference's order. Every
  // face's solid side is fixed by q0 (the probe's image lies in the tile):
  // spheres get solidInside = "q0 inside"; planes are re-normalized so the
  // solid side is n·p < h and the fold reflects on the other side.
  const senseOf = (img: HImage): SphairahedronFoldFace => {
    if (img.kind === "sphere") {
      return {
        face: { kind: "sphere", sphere: img.sphere },
        solidInside: dist(q0, img.sphere.c) < img.sphere.r,
      };
    }
    const pl = img.plane;
    if (dot(pl.n, q0) - pl.h > 0) {
      return {
        face: { kind: "plane", plane: { n: pl.n.map((v) => -v), h: -pl.h } },
        solidInside: false,
      };
    }
    return {
      face: { kind: "plane", plane: { n: [...pl.n], h: pl.h } },
      solidInside: false,
    };
  };
  const wallSensed = scene.faces
    .filter((f) => f.kind === "plane")
    .map((f) => senseOf(imageOfFace(f)));
  const ballSensed = scene.faces
    .filter((f) => f.kind === "sphere")
    .map((f) => senseOf(imageOfFace(f)));
  const foldFaces: SphairahedronFoldFace[] = [];
  const nb = ballSensed.length;
  const nw = wallSensed.length;
  for (let k = 0; k < Math.max(nb, nw); k++) {
    if (k < nw) foldFaces.push(wallSensed[k]);
    if (k < nb) foldFaces.push(ballSensed[k]);
  }

  // Framing: the divide plane's image grown to hold the dent spheres.
  const divideImage = invertPlane(j, scene.divide);
  let bound = { center: [...j.c], radius: j.r * 3 };
  if (divideImage.kind === "sphere") {
    const cv = divideImage.sphere.c;
    let radius = divideImage.sphere.r;
    for (const { face } of foldFaces) {
      if (face.kind !== "sphere") continue;
      radius = Math.max(radius, dist(face.sphere.c, cv) + face.sphere.r);
    }
    bound = { center: [...cv], radius: radius * 1.04 };
  }

  const seeds: SphairahedronSeedBall[] = scene.seeds.map((b) => {
    const img = invertSphere(j, b);
    if (img.kind !== "sphere")
      throw new Error("seed ball image degenerate; move the inversion sphere");
    return img.sphere;
  });

  const vertices: SphairahedronVertex[] = scene.vertices.map((v) => ({
    p: invertPoint(j, v.p),
    faces: v.faces,
  }));

  return {
    foldFaces,
    pieces,
    probe: q0,
    bound,
    seeds,
    vertices,
  };
}

