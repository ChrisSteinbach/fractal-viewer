export type SphairahedronEligibilityStatus =
  "eligible" | "degraded" | "ineligible";

export interface SphairahedronEligibility {
  /** `eligible`: marched at {@link SPHAIRAHEDRON_STEP_SCALE} with no
   * disclosure. `degraded`: still marched, with `degradations` naming what
   * costs (a region-boundary cusp, a capped-fold regime). `ineligible`: no
   * construction exists; see `reasons`. */
  status: SphairahedronEligibilityStatus;
  /** Blockers; non-empty exactly when `ineligible`. */
  reasons: string[];
  /** Disclosures; non-empty exactly when `degraded`. */
  degradations: string[];
}

/**
 * The construction-level gate, in the `analyzeSphereInversionSystem` shape.
 * Ineligible when the vectors or radii are malformed, a solved radius is
 * non-positive, the construction failed its Lemma verification, or the
 * moduli sit past the family's region. Degraded when a moduli pair sits ON
 * a region threshold (the two faces touch tangentially — a cusp the
 * marcher creeps at, the disjoint family's tangency disclosure) or when the
 * fold regime is known to stress (a construction whose balls cross walls
 * they do not bound — legal for the prism's second vertex and the tetra's
 * floor ball, disclosed when it is the region's own edge case).
 */
export function analyzeSphairahedronSystem(
  construction: SphairahedronConstruction,
): SphairahedronEligibility {
  const reasons: string[] = [];
  const degradations: string[] = [];
  const { dim, radii, verification, family } = construction;
  const done = (): SphairahedronEligibility => ({
    status:
      reasons.length > 0
        ? "ineligible"
        : degradations.length > 0
          ? "degraded"
          : "eligible",
    reasons,
    degradations: reasons.length > 0 ? [] : degradations,
  });
  if (dim !== 3 && dim !== 4) {
    reasons.push(`dimension ${String(dim)} is not 3 or 4`);
    return done();
  }
  if (!SPHAIRAHEDRON_FAMILIES.includes(family)) {
    reasons.push(`unknown family "${String(family)}"`);
    return done();
  }
  radii.forEach((r, i) => {
    if (!Number.isFinite(r)) reasons.push(`radius ${i + 1} is not finite`);
    else if (r <= SPHAIRAHEDRON_MIN_RADIUS)
      reasons.push(`radius ${i + 1} is ${r}: not a ball`);
  });
  for (const key of ["za", "zb", "z2"] as const) {
    const v = construction.moduli[key];
    if (v !== undefined && !Number.isFinite(v)) {
      reasons.push(`modulus ${key} is not finite`);
    }
  }
  if (verification.problems.length > 0) {
    reasons.push(...verification.problems);
  }
  reasons.push(
    ...regionRead(FAMILIES[family], ballNames(family), radii).reasons,
  );
  if (reasons.length > 0) return done();
  if (construction.regionBoundary) {
    degradations.push(
      "a ball face is tangent to a wall it does not bound (the moduli sit " +
        "on the region boundary): a cusp the marcher creeps at",
    );
  }
  return done();
}

function ballNames(family: SphairahedronFamilyId): readonly string[] {
  return family === "prism2"
    ? ["b2", "b4"]
    : family === "tetra333" || family === "tetra4"
      ? ["b"]
      : ["b2", "b4", "b6"];
}
