// ------------------------------------------------------------- geometry

/** Half-space boundary `n·p = h`; the REMOVED side is `n·p > h` (the fold
 * reflects across it, the tile excludes it). */
export interface SphairahedronPlane {
  n: readonly number[];
  h: number;
}

export type SphairahedronSphere = { c: readonly number[]; r: number };

export type SphairahedronFace =
  | { kind: "sphere"; sphere: SphairahedronSphere }
  | { kind: "plane"; plane: SphairahedronPlane };

/** One fold generator in SCAN ORDER with its sense: a face whose solid side
 * is the sphere's INTERIOR folds points that are OUTSIDE it (`d² > r²`),
 * not inside — getting this wrong silently folds points out of the tile and
 * renders garbage (the study's flagged defect). */
export interface SphairahedronFoldFace {
  face: SphairahedronFace;
  solidInside: boolean;
}

/** One max-form term of a tile piece; the solid is where the SDF <= 0.
 * Sphere: `inside` = the solid includes the ball's interior (SDF
 * `dist − r`), else the solid excludes it (SDF `r − dist`). Plane: `above`
 * = the solid side is `n·p > h` (SDF `h − n·p`), else `n·p < h`
 * (SDF `n·p − h`). */
export type SphairahedronTerm =
  | { kind: "sphere"; c: readonly number[]; r: number; inside: boolean }
  | { kind: "plane"; n: readonly number[]; h: number; above: boolean };

export interface SphairahedronTilePiece {
  terms: readonly SphairahedronTerm[];
}

/** A maximum vertex ball (the preprint's Def 4.1 seeds): the ball through a
 * vertex, orthogonal to every edge there, maximal along its centre line, on
 * the side that pokes into the tile. */
export interface SphairahedronSeedBall {
  c: readonly number[];
  r: number;
}

/** A construction vertex: its point and the combined face indices (balls
 * first, then walls) it joins. The finite construction carries the images. */
export interface SphairahedronVertex {
  p: readonly number[];
  faces: readonly number[];
}

export interface SphairahedronVerification {
  /** Lemma 3.3(2): |centre − corner| − r, and the Lemma 3.5 wall-circle
   * gap at the feet. */
  maxTangentErr: number;
  /** Lemma 3.3(3) as the plane/sphere dihedral: |acos(δ/r) − θ|. */
  maxAngleErr: number;
  /** Non-fatal construction notes (extra crossings live on the report's
   * `crossings`, not here). */
  problems: string[];
  /** Walls each ball crosses beyond its corner pair, by ball name. */
  crossings: Readonly<Record<string, readonly number[]>>;
}

