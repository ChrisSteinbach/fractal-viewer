/**
 * The sphairahedron family's ONE shared vocabulary, imported by both
 * estimator twins (`sphairahedron-de.ts`, `sphairahedron-de-4d.ts`): what a
 * construction IS has one definition across both dimensions, and only the
 * estimators' vector arithmetic is duplicated under the twin-file convention
 * (the `escape-de-4d.ts` rule). The construction, the region derivations and
 * the measurements behind every choice below are in
 * `docs/sphairahedron-family.md`; the pre-gate study's prototype
 * (`scripts/sphairahedron-orbit.ts`) is the independent record this module
 * was transcribed from and checked against.
 *
 * THE OBJECT. A wall system of three planes through the height axis bounds a
 * prism cross-section; excavation balls sit at its corners (Lemma 3.3: the
 * ball is tangent to the vertical corner line at the corner point at the
 * ball's own height, its centre at distance `r` along the wedge-interior
 * direction making the ball's dihedral angles with the wall solid-side
 * normals); radii solve the Lemma 3.5 tangency equations (one per ball pair
 * sharing a wall, LINEAR in the radii — exact elimination, no iteration).
 * The tile is the prism ∧ the divide plane (through the corner vertices)
 * minus the balls; a FINITE sphairahedron is the image of an infinite one
 * under one more inversion sphere `J` (every face maps to a sphere, or to a
 * plane when the face passes through `J`'s centre — handled, not refused).
 * The rendered set is the LIMIT SET Λ = ∂(∪ tiles) of the group generated by
 * the face involutions, rendered through the IIS fold + the accumulated-
 * Jacobian estimate (the estimator twins' module docs).
 *
 * TWO LAYERS, on the `sphere-inversion.ts` precedent:
 *
 *   - AUTHORED ({@link SphairahedronAuthored}): family id × the moduli the
 *     family reads × an optional inversion sphere (absent = the infinite
 *     construction, byte-identically for every document predating it).
 *   - RESOLVED ({@link SphairahedronConstruction}): the explicit fold faces
 *     in scan order, tile pieces, probe, divide, framing ball, seed balls
 *     and verification report the estimators and the analyzer read.
 *
 * {@link resolveSphairahedron} expands the first into the second in the
 * `resolveFoldRadii` style with the disjoint family's deliberate difference:
 * an out-of-region or unknown value is REFUSED with a reason, never clamped,
 * because a clamp would render a different object than the document names.
 * The resolver never mutates or normalizes its input.
 *
 * THE VALID REGION, DERIVED (not copied — the pdftotext extraction of the
 * 2020 preprint mangles coefficients, so every curve below was re-derived
 * from the construction and checked against the appendix's curve list): for
 * the cube families each appendix boundary curve IS one ball's tangency to
 * the wall it does not bound — the ball's sphere crossing that wall is the
 * tile-overlap failure mode, and the tangency is where it degenerates. The
 * thresholds fall out of the placement rule (centre at distance `r` along
 * the corner-to-origin direction; the untouched wall at fixed distance from
 * the corner): type 1 `r = 3/4` (all three balls), type 4 `r = 2√3−3, 4−2√3,
 * 4√3−6` (walls 2, 1, 0), type 9 `r = 1/2, 1/√2, 2√2−2`. Written in the
 * moduli these reproduce the appendix's curves exactly (constants checked:
 * `3zA²+6zA·zB+zB² = 36√3−60`, `15zA²−6zA·zB−zB² = 72√3−120`,
 * `3zA²+6zA·zB−5zB² = 120−72√3` for type 4; `2zA·zB+zB² = 1`,
 * `3zA²−2zA·zB−zB² = 2`, `zB²−zA·zB = 6√2−8` for type 9; `zA·zB = zA²−zA·zB
 * = zB²−zA·zB = 3/4` for type 1). For the prism the appendix's own derivation
 * (Prop 3.12) is the wall-circle fit `ρ < w/2`, which in radii reads
 * `r2 < 1` ⟺ `z2² < 6` — the region is the open interval `(−√6, √6)`. The
 * tetra families have no free moduli and no region. The region is OPEN: a
 * moduli pair ON a threshold still resolves (the construction verifies; the
 * two faces touch tangentially) and the analyzer marks it DEGRADED; past it
 * the resolver refuses with the failing ball named. The panel parameters the
 * owner approved all sit strictly inside (the past-cusp cube-1 sheet was the
 * study's deliberate outside-region rendering, harness-only).
 *
 * THE TWO REFERENCE-CODE DISCREPANCIES the pre-gate study named (CubeE's
 * region condition carries the author's own "It may contain mistake"
 * comment; CubeH's third inequality disagrees with the preprint by one
 * coefficient on zA²) are NOT copied: types 2/3/5/8 are not shipped, and the
 * shipped regions come from the derivation above.
 *
 * THE INVERSION SPHERE. A finite construction needs `J` — a FREE parameter
 * of the family (the quasi-sphere deforms continuously with it, measured in
 * the study), and it is AUTHORED EXPLICITLY: the resolver refuses a finite
 * request without one. There is no silent default, for a measured reason:
 * the reference implementation's constrained sphere (the mirror of the last
 * ball) and even its divide-reflected variant render the COMPLEMENT-POCKET
 * presentation for many parameters (the union is then the unbounded side
 * and the compact blob is too small to frame — the study's j-flip
 * exploration), and the rule that actually produced the owner-approved
 * sheets is the study's deterministic picker, which SAMPLES THE DE SIGN and
 * so cannot live in this pure module. {@link defaultSphairahedronInversion}
 * exposes the reflected-reference rule as the picker's documented FIRST
 * CANDIDATE (an authoring aid for the panel child, which owns the picker);
 * documents carry explicit spheres. A J that degenerates the construction
 * (a seed image that is not a sphere) is refused.
 *
 * PERSISTENCE DESIGN (the wiring lands with the panel/persistence child; the
 * block's contract is decided here): a scene-document block
 * `sphairahedron?: SphairahedronAuthored` on the `sphereInversion` block's
 * precedent — encoded only when present, decoded strictly never-throwing,
 * a refused block carried VERBATIM so a newer document's fields survive an
 * older version's round trip. Unknown keys refuse at RESOLVE time (named),
 * never at decode; absence of the block is the classic transform-system
 * scene byte-identically. The authored fields are exactly
 * {@link SPHAIRAHEDRON_AUTHORED_FIELDS}; every numeric leaf must be finite;
 * values are of any JSON type (an imported document is untrusted) and a
 * wrongly typed value refuses like an out-of-domain one.
 *
 * MORPH STANCE (decided here, wired by the morph child): a morph between two
 * sphairahedron documents of the SAME family lerps the moduli (and, between
 * two finite constructions, the inversion sphere's centre and radius — the
 * quasi-sphere deforms continuously with J, measured in the study) and
 * resolves intermediates through {@link buildSphairahedron}, the
 * construction-existence path, NOT the document resolver — because the valid
 * region is NOT convex (the cube-1 cusp `(√6/4, √6/2)` and its moduli swap
 * are both in-region; their midpoint is not), so a region gate on midpoints
 * would break a legal morph mid-glide. Out-of-region intermediates render
 * coherently (measured: the past-cusp parameters fold with the same
 * statistics, cap never reached). Endpoints are exact: `t = 0/1` resolve to
 * the endpoints' own constructions. Cross-family or infinite↔finite pairs
 * have no meaningful interpolation — the morph is a replace-load, disclosed
 * by the morph driver like any other subject replacement.
 *
 * MUTATION STANCE (decided here, wired by the mutation child): the mutation
 * grid authors no moduli and no family changes — `mutateSystem` preserves
 * the block untouched, wildcard included, on the random-system precedent
 * (it authors no parameters it cannot defend: the region inequalities are
 * exactly what a random nudge cannot guarantee).
 *
 * THE 4D STANCE (the study's, carried forward): the fold, the inversion
 * algebra and the estimators are dimension-free and run at n = 4 unchanged;
 * the shipped 4D family is the tetra lift (the 333 wall hyperplanes, the
 * unit 3-ball at the origin, the tile cut by the invariant hyperplane
 * y = 0), whose limit set is the image of that hyperplane — an analytic
 * 3-sphere once finite. Discreteness for a 4D cell is NOT claimed: the
 * preprint's own 4D classification is open. The slice-then-invert idioms of
 * the disjoint family do NOT transfer here — there is no echo to project; a
 * 4D sphairahedron is its own construction.
 */
